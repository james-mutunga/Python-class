# This program will ask for the user's name and then greet them.

# We start by using the input() function to take user input as a string. The input() function displays a prompt to the user and waits for them to enter their name.
# We then store the user's input in a variable called 'name'.
# Finally, we use the print() function to display a greeting message that includes the user's name. We concatenate the string "Hello, " with the user's name to create a personalized greeting. 

name = input("Enter your name: ")

print("Hello, " + name)