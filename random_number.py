# This program will generate a random number between 1 and 100 and print it to the console.

# We start by importing the random module, which contains functions for generating random numbers.
# We use the randint() function from the random module to generate a random integer between 1 and 100, inclusive.

import random
number = random.randint(1, 100)

# Finally, we print the generated random number to the console using the print() function.

print (number)