# What will be the data type of the following expressions?

# These are the fixed data types

width = 17
height = 12.0

print(type(width//2))

# this will be an interger because we are using the floor division operator (//), which truncates the decimal part and returns an integer result.

# result int

print(type(width/2.0))

# result float

print(type(height/3))

# result float

print(type(1 + 2 * 5))

# result int